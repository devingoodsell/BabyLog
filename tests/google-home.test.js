const { spawn } = require('child_process');
const MOCK = 'http://localhost:' + process.env.PORT;
let fails = 0; const check = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const code = (await (await fetch(MOCK + '/__invite')).text()).match(/#invite=([a-f0-9]+)/)[1];
  const red = await (await fetch(MOCK + '/exec', { method: 'POST', body: JSON.stringify({ action: 'redeem', code, name: 'Google Home' }) })).json();
  check(red.ok && red.me.name === 'Google Home', 'service gets its own "Google Home" key');
  const env = { ...process.env, PORT: String(Number(process.env.PORT) + 1000), CLIENT_ID: 'babylog-abc', CLIENT_SECRET: 'sek', SIGNING_KEY: 'k'.repeat(64), LINK_PASSCODE: 'ABCD-EFGH', BABYLOG_API: MOCK + '/exec', BABYLOG_TOKEN: red.token };
  const srv = spawn('node', [require('path').join(__dirname, '..', 'google-home', 'server.js')], { env, stdio: ['ignore', 'pipe', 'pipe'] });
  let logs = ''; srv.stdout.on('data', d => logs += d); srv.stderr.on('data', d => logs += d);
  await sleep(600);
  const S = 'http://localhost:' + (Number(process.env.PORT) + 1000);
  const redirect = 'https://oauth-redirect.googleusercontent.com/r/my-project';
  const q = new URLSearchParams({ client_id: 'babylog-abc', redirect_uri: redirect, state: 'xyz', response_type: 'code' });
  let r = await fetch(S + '/oauth/authorize?' + q);
  check(r.status === 200 && (await r.text()).includes('Link Baby Log'), 'link page shows');
  r = await fetch(S + '/oauth/authorize?' + new URLSearchParams({ ...Object.fromEntries(q), redirect_uri: 'https://evil.example.com/cb' }));
  check(r.status === 400, 'unknown redirect address is refused');
  r = await fetch(S + '/oauth/authorize', { method: 'POST', body: new URLSearchParams({ ...Object.fromEntries(q), passcode: 'WRONG-PASS' }), redirect: 'manual' });
  check(r.status === 200 && (await r.text()).includes('not right'), 'wrong passcode is refused');
  r = await fetch(S + '/oauth/authorize', { method: 'POST', body: new URLSearchParams({ ...Object.fromEntries(q), passcode: 'abcd efgh' }), redirect: 'manual' });
  const loc = new URL(r.headers.get('location'));
  check(r.status === 302 && loc.origin + loc.pathname === redirect && loc.searchParams.get('state') === 'xyz', 'right passcode redirects back to Google with a code');
  const authCode = loc.searchParams.get('code');
  r = await fetch(S + '/oauth/token', { method: 'POST', body: new URLSearchParams({ grant_type: 'authorization_code', code: authCode, client_id: 'babylog-abc', client_secret: 'bad', redirect_uri: redirect }) });
  check(r.status === 401, 'wrong client secret is refused');
  r = await fetch(S + '/oauth/token', { method: 'POST', headers: { Authorization: 'Basic ' + Buffer.from('babylog-abc:sek').toString('base64') }, body: new URLSearchParams({ grant_type: 'authorization_code', code: authCode, redirect_uri: redirect }) });
  const tok = await r.json();
  check(r.status === 200 && tok.access_token && tok.refresh_token && tok.expires_in === 3600, 'code exchanges for tokens (Basic auth)');
  r = await fetch(S + '/oauth/token', { method: 'POST', body: new URLSearchParams({ grant_type: 'refresh_token', refresh_token: tok.refresh_token, client_id: 'babylog-abc', client_secret: 'sek' }) });
  const tok2 = await r.json();
  check(r.status === 200 && tok2.access_token && !tok2.refresh_token, 'refresh token gives a new access token');
  r = await fetch(S + '/oauth/token', { method: 'POST', body: new URLSearchParams({ grant_type: 'refresh_token', refresh_token: tok.access_token, client_id: 'babylog-abc', client_secret: 'sek' }) });
  check(r.status === 400, 'an access token cannot be used as a refresh token');
  const call = (body, t = tok2.access_token) => fetch(S + '/fulfillment', { method: 'POST', headers: { Authorization: 'Bearer ' + t, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  r = await call({ requestId: 'r1', inputs: [{ intent: 'action.devices.SYNC' }] }, 'nope');
  check(r.status === 401, 'fulfillment without a valid token is refused');
  r = await call({ requestId: 'r1', inputs: [{ intent: 'action.devices.SYNC' }] });
  const sync = await r.json();
  const names = sync.payload.devices.map(d => d.name.name);
  console.log('    ' + names.join('\n    '));
  check(names.length === 15 && sync.payload.devices.every(d => d.type === 'action.devices.types.SCENE'), 'SYNC lists 15 scenes');
  check(names.includes('Baby Log dirty and wet diaper') && names.includes('Baby Log bottle feed 1 ounce of formula') && names.includes('Baby Log bottle feed 8 ounces of breast milk'), 'scene names match the phrases');
  check(new Set(sync.payload.devices.map(d => d.id)).size === 15, 'scene ids are unique');
  r = await call({ requestId: 'r2', inputs: [{ intent: 'action.devices.QUERY', payload: { devices: [{ id: 'diaper-wet' }] } }] });
  check((await r.json()).payload.devices['diaper-wet'].online === true, 'QUERY answers');
  const exec = (rid, id) => call({ requestId: rid, inputs: [{ intent: 'action.devices.EXECUTE', payload: { commands: [{ devices: [{ id }], execution: [{ command: 'action.devices.commands.ActivateScene', params: { deactivate: false } }] }] } }] });
  const t0 = Date.now();
  r = await exec('e1', 'diaper-wet');
  const ex = await r.json();
  check(ex.payload.commands[0].status === 'SUCCESS', 'EXECUTE wet diaper succeeds (' + (Date.now() - t0) + ' ms)');
  await exec('e1', 'diaper-wet');                // Google retrying the same request
  await exec('e2', 'diaper-both');
  r = await exec('e4', 'bottle-formula-6oz');
  check((await r.json()).payload.commands[0].status === 'SUCCESS', 'bottle preset succeeds');
  await exec('e5', 'bottle-breast-1oz');
  r = await exec('e3', 'not-a-scene');
  check((await r.json()).payload.commands[0].errorCode === 'deviceNotFound', 'unknown device is rejected');
  const st = await (await fetch(MOCK + '/__state')).json();
  const rows = st.Log.slice(1).filter(x => x[1]);
  check(rows.filter(x => x[1] === 'Wet diaper').length === 1, 'a retried command does not log twice');
  check(rows.some(x => x[1] === 'Wet + dirty diaper' && x[8] === 'Google Home'), 'entries are stamped "Google Home"');
  check(rows.some(x => x[1] === 'Bottle' && x[4] === 6 && x[12] === 6 && x[13] === 'oz' && x[14] === 'Formula'), '6 oz formula bottle row is complete');
  check(rows.some(x => x[1] === 'Bottle' && x[4] === 1 && x[14] === 'Breast milk'), '1 oz breast milk bottle row is complete');
  const wet = rows.find(x => x[1] === 'Wet diaper');
  check(wet && Math.abs(new Date(wet[0]) - t0) < 5000, 'entry time is when it was said');
  check(!logs.includes(red.token) && !logs.includes('sek'), 'secrets never appear in the service logs');
  srv.kill();
  console.log(fails ? fails + ' FAILURES' : 'ALL PASSED');
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
